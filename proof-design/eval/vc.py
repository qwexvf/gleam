"""Hand-written verification conditions for each design pattern.

Each check negates the postcondition and asks Z3 for a model: unsat = proved,
sat = counterexample, unknown = solver gave up within the timeout.
These are written by hand from the patterns, not generated by a compiler,
so they show what an encoder would have to emit, not that one exists.
"""
import time
from z3 import (Int, Ints, Solver, And, Or, Not, Implies, If, ForAll, IntVal,
                Datatype, IntSort, BoolSort, RecFunction, RecAddDefinition, Const,
                Length, SeqSort, FP, FPSort, fpAdd, fpEQ, fpIsInf,
                fpIsNaN, RNE, FPVal, simplify, sat, unsat)

TIMEOUT_MS = 5000
results = []


def check(name, *facts, negated_goal):
    s = Solver()
    s.set("timeout", TIMEOUT_MS)
    s.add(*facts, Not(negated_goal))
    t = time.perf_counter()
    r = s.check()
    ms = (time.perf_counter() - t) * 1000
    if r == unsat:
        verdict = "PROVED"
    elif r == sat:
        m = s.model()
        shown = ", ".join(f"{d.name()}={m[d]}" for d in m.decls() if d.arity() == 0)
        verdict = f"COUNTEREXAMPLE {shown}"
    else:
        verdict = f"UNKNOWN ({s.reason_unknown()})"
    results.append((name, verdict, ms))


# E1 linear contract: withdraw
b, a, r = Ints("b a r")
check("E1 withdraw requires a<=b",
      b >= 0, a > 0, a <= b, r == b - a, negated_goal=r >= 0)
check("E1 withdraw missing a<=b",
      b >= 0, a > 0, r == b - a, negated_goal=r >= 0)

# E2 opaque type invariant: every constructor site inside the module must
# establish it, every function outside may assume it.
x = Int("x")
check("E2 deposit preserves Balance invariant",
      b >= 0, x > 0, r == b + x, negated_goal=r >= 0)
check("E2 new() only builds Balance on the x>=0 branch",
      Implies(x >= 0, r == x), x >= 0, negated_goal=r >= 0)

# E3 recursion: sum of a non-negative list
L = Datatype("L")
L.declare("nil")
L.declare("cons", ("hd", IntSort()), ("tl", L))
L = L.create()
l = Const("l", L)
sum_ = RecFunction("sum", L, IntSort())
RecAddDefinition(sum_, [l], If(L.is_nil(l), 0, L.hd(l) + sum_(L.tl(l))))
allnn = RecFunction("allnn", L, BoolSort())
RecAddDefinition(allnn, [l], If(L.is_nil(l), True,
                                And(L.hd(l) >= 0, allnn(L.tl(l)))))
check("E3a whole-program: forall l. allnn(l) -> sum(l)>=0 (needs induction)",
      negated_goal=ForAll([l], Implies(allnn(l), sum_(l) >= 0)))
# Modular: the recursive call is replaced by its own ensures clause.
h, rest_sum = Ints("h rest_sum")
check("E3b modular: assume ensures of recursive call",
      h >= 0, rest_sum >= 0, r == h + rest_sum, negated_goal=r >= 0)

# E4 list index bounds via sequence theory
xs = Const("xs", SeqSort(IntSort()))
i = Int("i")
check("E4 caller guard i>=0 && i<length(xs) meets at() precondition",
      i >= 0, i < Length(xs), negated_goal=And(0 <= i, i < Length(xs)))
check("E4 caller guard i<=length(xs) (off by one)",
      i >= 0, i <= Length(xs), negated_goal=And(0 <= i, i < Length(xs)))

# E5 division semantics: Gleam on Erlang truncates toward zero and x/0 == 0.
results.append(("E5 Z3 built-in (-7)/2", f"= {simplify(IntVal(-7) / 2)}"
                " (Erlang div gives -3)", 0.0))


def gleam_div(p, q):
    t = If(p >= 0, If(q > 0, p / q, -(p / -q)),
           If(q > 0, -((-p) / q), (-p) / (-q)))
    return If(q == 0, 0, t)


p, q = Ints("p q")
check("E5 gleam_div(-7,2) == -3 under the Gleam encoding",
      p == -7, q == 2, negated_goal=gleam_div(p, q) == -3)
check("E5 (p/q)*q <= p with Z3 built-in division",
      p == -7, q == 2, negated_goal=(p / q) * q <= p)
check("E5 (p/q)*q <= p with Gleam division",
      p == -7, q == 2, negated_goal=gleam_div(p, q) * q <= p)

# E6 nonlinear arithmetic
n, w, hh = Ints("n w hh")
check("E6 w>=0,h>=1 -> w*h >= w",
      w >= 0, hh >= 1, r == w * hh, negated_goal=r >= w)
check("E6 n*(n+1) is even",
      r == n * (n + 1), negated_goal=r % 2 == 0)

# E7 JavaScript target: Gleam Int is an IEEE double there.
F = FPSort(11, 53)
fx = FP("fx", F)
one = FPVal(1.0, F)
check("E7 JS Int: x + 1 != x for every finite x",
      Not(fpIsInf(fx)), Not(fpIsNaN(fx)),
      negated_goal=Not(fpEQ(fpAdd(RNE(), fx, one), fx)))
check("E7 Erlang Int: x + 1 != x",
      negated_goal=x + 1 != x)

if __name__ == "__main__":
    for name, verdict, ms in results:
        print(f"{ms:8.1f} ms  {name}\n             {verdict}")
